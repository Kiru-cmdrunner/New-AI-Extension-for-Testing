// STATE SNAPSHOT + STATE DIFF
// ════════════════════════════════════════════════════════════════════════

/**
 * A complete snapshot of observable DOM state at a point in time.
 *
 * PRODUCED BY: StateDiffEngine (before and after each interaction unit)
 */
export interface StateSnapshot {
  readonly timestamp: string;
  readonly url: string;
  readonly pageTitle: string;

  // ── Form State ──
  readonly inputs: InputFieldState[];
  readonly checkboxes: ToggleState[];
  readonly radios: RadioGroupState[];
  readonly toggles: ToggleState[];
  readonly ranges: RangeState[];

  // ── Focus State ──
  readonly focusedElement: ElementDescriptor | null;

  // ── Structural State ──
  readonly openSurfaces: OpenSurfaceState[];
  readonly activeTab: TabState | null;
  readonly expandedAccordions: ElementDescriptor[];

  // ── DOM Structural State ──
  /** Count of visible interactive elements (for structural change detection). */
  readonly interactiveElementCount: number;
}

export interface InputFieldState {
  readonly descriptor: ElementDescriptor;
  readonly value: string;
  readonly inputType: string;
}

export interface ToggleState {
  readonly descriptor: ElementDescriptor;
  readonly checked: boolean;
}

export interface RadioGroupState {
  readonly name: string;
  readonly descriptor: ElementDescriptor;
  readonly selectedOption: ElementDescriptor | null;
  readonly options: ElementDescriptor[];
}

export interface RangeState {
  readonly descriptor: ElementDescriptor;
  readonly value: string;
  readonly min: string;
  readonly max: string;
}

export interface OpenSurfaceState {
  readonly type: SurfaceType;
  readonly descriptor: ElementDescriptor;
}

export interface TabState {
  readonly selectedTab: ElementDescriptor;
  readonly activePanel: ElementDescriptor;
}

/**
 * The structured difference between two StateSnapshots.
 *
 * This is the PRIMARY SIGNAL for intent resolution. The Intent Resolver
 * consults the StateDiff first; patterns are accelerators.
 *
 * PRODUCED BY: StateDiffEngine
 * CONSUMED BY: PatternRegistry, InteractionAssembler, IntentResolver
 */
export interface StateDiff {
  readonly valueChanges: ValueChange[];
  readonly toggleChanges: ToggleChange[];
  readonly radioChanges: RadioChange[];
  readonly rangeChanges: RangeChange[];
  readonly focusChange: FocusChange | null;
  readonly surfaceChanges: SurfaceChange[];
  readonly tabChange: TabChange | null;
  readonly urlChange: UrlChange | null;
  readonly structuralChangeDetected: boolean;
}

export interface ValueChange {
  readonly descriptor: ElementDescriptor;
  readonly field: string;
  readonly before: string;
  readonly after: string;
  readonly inputType: string;
}

export interface ToggleChange {
  readonly descriptor: ElementDescriptor;
  readonly field: string;
  readonly before: boolean;
  readonly after: boolean;
}

export interface RadioChange {
  readonly groupName: string;
  readonly groupDescriptor: ElementDescriptor;
  readonly before: ElementDescriptor | null;
  readonly after: ElementDescriptor | null;
}

export interface RangeChange {
  readonly descriptor: ElementDescriptor;
  readonly field: string;
  readonly before: string;
  readonly after: string;
}

export interface FocusChange {
  readonly from: ElementDescriptor | null;
  readonly to: ElementDescriptor | null;
}

export interface SurfaceChange {
  readonly type: SurfaceType;
  readonly action: 'opened' | 'closed';
  readonly descriptor: ElementDescriptor;
}

export interface TabChange {
  readonly from: ElementDescriptor;
  readonly to: ElementDescriptor;
}

export interface UrlChange {
  readonly from: string;
  readonly to: string;
}

// ════════════════════════════════════════════════════════════════════════
// PATTERN MATCH
// ════════════════════════════════════════════════════════════════════════

/**
 * The result of matching an interaction unit against the Pattern Registry.
 *
 * The Pattern Registry contains ~12 GENERIC interaction behaviors (not
 * framework-specific component patterns). A match is an accelerator:
 * it speeds up resolution and increases confidence, but it is NOT required.
 * The Intent Resolver produces a business action from the StateDiff alone
 * even when no pattern matches.
 *
 * PRODUCED BY: PatternRegistry
 * CONSUMED BY: InteractionAssembler, IntentResolver
 */
export interface PatternMatch {
  /** The generic behavior that matched (e.g. 'single-selection-from-set'). */
  readonly behavior: InteractionBehavior;

  /** Confidence that this pattern correctly describes the interaction. */
  readonly confidence: number;

  /** Human-readable rationale for why this pattern matched. */
  readonly rationale: string;

  /** Pattern-specific metadata extracted during matching. */
  readonly metadata: PatternMetadata;
}

/**
 * The generic interaction behaviors the Pattern Registry recognizes.
 *
 * These represent fundamental user intentions, NOT UI component types.
 * 'single-selection-from-set' covers native <select>, Material UI Select,
 * Ant Design Select, Radix Select, radio groups, and custom dropdowns —
 * because they all produce the same observable behavior.
 */
export type InteractionBehavior =
  | 'single-selection-from-set'  // Pick one option from a group
  | 'multi-selection-from-set'   // Pick multiple options
  | 'boolean-toggle'             // Flip a yes/no state
  | 'text-entry-commit'          // Enter or modify text
  | 'date-time-selection'        // Pick a date/time
  | 'expand-collapse'            // Open/close a section
  | 'context-switch'             // Move between views (tabs)
  | 'navigation'                 // Move to a new URL
  | 'hover-intent'               // Hover to reveal content
  | 'simple-click'               // Click with no complex state change
  | 'form-submit'                // Submit a form
  | 'generic-fallback';          // Unknown control — state diff only

/**
 * Pattern-specific metadata extracted during matching.
 * Different behaviors populate different fields.
 */
export interface PatternMetadata {
  /** Selected value (for selection behaviors). */
  readonly selectedValue?: string;
  /** Previous value (for selection behaviors). */
  readonly previousValue?: string;
  /** Selected option descriptor (for selection behaviors). */
  readonly selectedOption?: ElementDescriptor;
  /** Entered text value (for text-entry). */
  readonly textValue?: string;
  /** Toggle state (for boolean-toggle). */
  readonly toggleState?: boolean;
  /** Date display value (for date-time-selection). */
  readonly dateValue?: string;
  /** ISO date value (for date-time-selection). */
  readonly dateIsoValue?: string;
  /** Surface type (for expand-collapse). */
  readonly surfaceType?: SurfaceType;
  /** Input type of the changed element (for single-selection). */
  readonly inputType?: string;
}

// ════════════════════════════════════════════════════════════════════════
// RESOLVED ACTION — Intent Resolver Output
// ════════════════════════════════════════════════════════════════════════

/**
 * The final resolved business action.
 *
 * The Intent Resolver ALWAYS produces one of these, even for unknown controls.
 * For unrecognized controls, it uses the 'generic-fallback' behavior and
 * resolves from the StateDiff alone, with LOW confidence.
 *
 * PRODUCED BY: IntentResolver
 * CONSUMED BY: PipelineV2.toSessionEvent()
 */
export interface ResolvedAction {
  /** The resolved interaction behavior. */
  readonly behavior: InteractionBehavior;

  /** The SessionEvent type this action maps to. */
  readonly sessionEventType: SessionEventType;

  /** Confidence in the resolution (0.0 to 1.0). */
  readonly confidence: number;

  /** The element identity for the SessionEvent. */
  readonly elementIdentity: ElementIdentity | null;

  /** Type-specific fields for the SessionEvent. */
  readonly fields: ResolvedActionFields;

  /** Human-readable description of the resolved action. */
  readonly description: string;

  /** Why the resolver chose this action (for tracing). */
  readonly rationale: string;
}

/**
 * The SessionEvent type values (matches shared/types.ts union).
 */
export type SessionEventType =
  | 'navigation'
  | 'click'
  | 'text'
  | 'hover'
  | 'checkbox'
  | 'radio'
  | 'select'
  | 'dateSelect';

/**
 * Type-specific fields carried on the resolved action.
 * These map directly to SessionEvent variant fields.
 */
export interface ResolvedActionFields {
  readonly value?: string;
  readonly checked?: boolean;
  readonly dateType?: string;
  readonly displayValue?: string;
  readonly isoValue?: string;
  readonly url?: string;
  readonly title?: string;
}

