/**
 * A single trace entry showing an event's journey through one pipeline layer.
 *
 * LEARNING 5 (Runtime Traceability): The previous implementation had no way
 * to debug the flow. This trace system makes every event's path through
 * the pipeline visible.
 *
 * PRODUCED BY: PipelineTracer (called by each layer)
 * VISIBLE IN: DevTools console + side panel trace view
 */
export interface TraceEntry {
  readonly timestamp: string;
  readonly layer: TraceLayer;
  readonly eventId?: string;
  readonly unitId?: string;
  readonly action: string;
  readonly input: string;
  readonly output: string;
  readonly durationMs: number;
  readonly decision?: string;
}

export type TraceLayer =
  | 'event-capture'
  | 'boundary-detection'
  | 'state-diff'
  | 'pattern-registry'
  | 'interaction-assembler'
  | 'intent-resolver'
  | 'pipeline-output';

/**
 * Trace level controls verbosity.
 */
export type TraceLevel = 'off' | 'errors-only' | 'normal' | 'verbose';
