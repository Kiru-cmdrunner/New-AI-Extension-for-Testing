/**
 * Locator Ranking Tests — Phase 11 Milestone 11.1
 *
 * Tests the shared locator ranking logic extracted from resolveLocatorsForIR().
 * Verifies that both recording-time and execution-time paths produce identical
 * ranking results for the same candidates.
 */

import { describe, it, expect } from 'vitest';
import {
  rankLocatorCandidates,
  filterValidCandidates,
  extractCandidatesFromIdentity,
  isAutoGeneratedId,
  isCssInJsClass,
  LocatorCategory,
  type LocatorCandidate,
} from '../src/domain/locator-ranking';
import { LocatorStrategyType } from '../src/domain/enums';
import type { ElementIdentity } from '../src/shared/types';

// ── Helpers ──────────────────────────────────────────────────

function makeIdentity(overrides: Partial<ElementIdentity> = {}): ElementIdentity {
  return {
    accessibleName: 'Submit',
    ariaRole: 'button',
    ariaLabel: null,
    ariaLabelledBy: null,
    placeholder: null,
    tag: 'BUTTON',
    className: 'btn btn-primary',
    name: null,
    stableId: null,
    testId: null,
    dataCy: null,
    dataQa: null,
    cssSelector: 'button.btn-primary',
    xPath: '/html/body/div/button',
    inIframe: false,
    shadowDom: false,
    elementId: 'elem-0001',
    ...overrides,
  };
}

// ── Auto-Generated ID Detection ──────────────────────────────

describe('isAutoGeneratedId', () => {
  it('detects React auto-generated IDs', () => {
    expect(isAutoGeneratedId('react-123')).toBe(true);
    expect(isAutoGeneratedId('react-1.2.3')).toBe(true);
  });

  it('detects MUI auto-generated IDs', () => {
    expect(isAutoGeneratedId('mui-42')).toBe(true);
  });

  it('detects styled-components IDs', () => {
    expect(isAutoGeneratedId('sc-abc123')).toBe(true);
    expect(isAutoGeneratedId('css-abc123')).toBe(true);
  });

  it('detects Angular auto-generated IDs', () => {
    expect(isAutoGeneratedId('ng-xyz')).toBe(true);
    expect(isAutoGeneratedId('cdk-overlay-1')).toBe(true);
  });

  it('detects hex hash IDs (16+ chars)', () => {
    expect(isAutoGeneratedId('a1b2c3d4e5f6a7b8')).toBe(true);
  });

  it('does NOT flag stable business IDs', () => {
    expect(isAutoGeneratedId('submit-button')).toBe(false);
    expect(isAutoGeneratedId('email-input')).toBe(false);
    expect(isAutoGeneratedId('login-form')).toBe(false);
  });

  it('does NOT flag empty or short values', () => {
    expect(isAutoGeneratedId('')).toBe(false);
    expect(isAutoGeneratedId('btn')).toBe(false);
  });
});

